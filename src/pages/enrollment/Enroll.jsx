function Enroll() {
  const { isLoggedIn, checking } = useAuth();

  const [fullName, setFullName] = useState("");
  const [gender, setGender] = useState("");
  const [program, setProgram] = useState("");
  const [matricNumber, setMatricNumber] = useState("");
  const [imageSlots, setImageSlots] = useState(Array(MAX_IMAGES).fill(null));
  const [preview, setPreview] = useState(null);
  const [previewIndex, setPreviewIndex] = useState(0);
  const [dragOverIndex, setDragOverIndex] = useState(null);
  const [cameraSlotIndex, setCameraSlotIndex] = useState(null);
  const [loading, setLoading] = useState(false);
  const [checkingEnrollment, setCheckingEnrollment] = useState(true);
  const [alreadyEnrolled, setAlreadyEnrolled] = useState(false);
  const [enrollmentInProgress, setEnrollmentInProgress] = useState(false);
  const [isReenrolling, setIsReenrolling] = useState(false);
  const [enrolledFaceCount, setEnrolledFaceCount] = useState(0);
  const [enrollmentCheckError, setEnrollmentCheckError] = useState("");
  const [error, setError] = useState("");
  const [success, setSuccess] = useState(null);
  const previewUrls = useRef(new Set());

  useEffect(() => {
    if (!isLoggedIn) return;
    let cancelled = false;
    apiEnrollmentStatus()
      .then(status => {
        if (cancelled) return;
        setAlreadyEnrolled(status.enrolled);
        setEnrollmentInProgress(status.in_progress || false);
        setEnrolledFaceCount(status.face_count || 0);
      })
      .catch(err => { if (!cancelled) setEnrollmentCheckError(err.message); })
      .finally(() => { if (!cancelled) setCheckingEnrollment(false); });
    return () => { cancelled = true; };
  }, [isLoggedIn]);

  useEffect(() => () => {
    previewUrls.current.forEach(url => URL.revokeObjectURL(url));
  }, []);

  const releasePreview = url => {
    if (!url) return;
    URL.revokeObjectURL(url);
    previewUrls.current.delete(url);
  };

  const clearImages = () => {
    previewUrls.current.forEach(url => URL.revokeObjectURL(url));
    previewUrls.current.clear();
    setImageSlots(Array(MAX_IMAGES).fill(null));
    setPreview(null);
    setPreviewIndex(0);
  };

  if (!isLoggedIn) return <PublicEnrollmentPage />;
  if (checking) {
    return <div className={styles.enrollmentStatusPage}><FiLoader className={styles.enrollmentStatusSpinner} size={24}/><span>Checking your secure session...</span></div>;
  }

  if (checkingEnrollment) {
    return <div className={styles.enrollmentStatusPage}><FiLoader className={styles.enrollmentStatusSpinner} size={24}/><span>Checking your enrollment status...</span></div>;
  }

  if (enrollmentCheckError) {
    return (
      <div className={styles.enrollmentStatusPage}>
        <div className={styles.enrollmentStatusCard}>
          <FiAlertTriangle size={24}/><h1>Could not check enrollment</h1><p>{enrollmentCheckError}</p>
          <button type="button" className="btn btn-primary" onClick={() => window.location.reload()}>Try again</button>
        </div>
      </div>
    );
  }

  if (alreadyEnrolled) {
    const startReenrollment = () => {
      const confirmed = window.confirm(
        "Re-enroll with new photos? Your current enrollment will remain active unless the new enrollment succeeds.",
      );
      if (!confirmed) return;
      setIsReenrolling(true);
      setAlreadyEnrolled(false);
      setFullName("");
      setGender("");
      setProgram("");
      setMatricNumber("");
      setError("");
      setSuccess(null);
    };

    return (
      <div className={styles.enrollmentStatusPage}>
        <div className={styles.enrollmentStatusCard}>
          <span className={styles.enrollmentStatusSuccess}><FiCheckCircle size={24}/></span>
          <div className={styles.enrollmentStatusEyebrow}>{enrollmentInProgress ? "ENROLLMENT IN PROGRESS" : success && isReenrolling ? "RE-ENROLLMENT COMPLETE" : "ENROLLMENT COMPLETE"}</div>
          {success ? (
            <>
              <div className={styles.workspaceEyebrow}><i /> PROFILE READY</div>
              <h1>Enrollment Successful</h1>
              <p>Your facial profile has been created successfully and is now available for identity recognition.</p>
              <div className={styles.successDetails}>
                <span>{success.records.length} face image{success.records.length === 1 ? "" : "s"} saved</span>
                {success.records[0]?.full_name && <span>Name: {success.records[0].full_name}</span>}
                {success.records.map(record => record.enrolled_id && <span key={record.enrolled_id}>Enrollment ID: {record.enrolled_id}</span>)}
              </div>
              <div className={styles.statusActions}>
                <Link to="/dashboard" className={styles.secondaryButton}>View Dashboard <FiArrowRight /></Link>
                <Link to="/verification" className={styles.primaryButton}>Continue to Verification <FiArrowRight /></Link>
                <button type="button" className={styles.textButton} onClick={startReenrollment}>Replace Enrollment Images</button>
              </div>
            </>
          ) : enrollmentInProgress ? (
            <>
              <div className={styles.workspaceEyebrow}><i /> ENROLLMENT IN PROGRESS</div>
              <h1>Your enrollment is being processed</h1>
              <p>An enrollment request for this account is already being completed. Please wait before trying again.</p>
            </>
          ) : (
            <>
              <div className={styles.workspaceEyebrow}><i /> PROFILE ACTIVE</div>
              <h1>Your facial profile is already active</h1>
              <p>{enrolledFaceCount} face image{enrolledFaceCount === 1 ? "" : "s"} are saved{fullName ? ` for ${fullName}` : " for your account"} and available for recognition.</p>
              <div className={styles.statusActions}>
                <Link to="/dashboard" className={styles.secondaryButton}>View Dashboard <FiArrowRight /></Link>
                <Link to="/verification" className={styles.primaryButton}>Continue to Verification <FiArrowRight /></Link>
                <button type="button" className={styles.textButton} onClick={startReenrollment}>Replace Enrollment Images</button>
              </div>
            </>
          )}
        </div>
      </div>
    );
  }

  const selectedSlots = imageSlots.filter(Boolean);
  const handleSlotChange = (index, file) => {
    if (!file) return false;
    if (file.size > MAX_IMAGE_SIZE_BYTES) {
      setError("Max file size is 100KB. Please choose a smaller image.");
      return false;
    }
    const ext = file.name.split(".").pop()?.toLowerCase();
    if (!["jpg", "jpeg", "png"].includes(ext || "")) {
      setError("Please upload a JPG or PNG image.");
      return false;
    }
    const updatedSlots = [...imageSlots];
    if (updatedSlots[index]) releasePreview(updatedSlots[index].previewUrl);
    const previewUrl = URL.createObjectURL(file);
    previewUrls.current.add(previewUrl);
    updatedSlots[index] = { file, previewUrl };
    setImageSlots(updatedSlots);
    const currentIndex = updatedSlots.filter(Boolean).findIndex(slot => slot.previewUrl === previewUrl);
    setPreview(previewUrl);
    setPreviewIndex(currentIndex >= 0 ? currentIndex : 0);
    setSuccess(null);
    setError("");
    return true;
  };

  const handleRemoveSlot = (index) => {
    const updatedSlots = [...imageSlots];
    if (updatedSlots[index]) releasePreview(updatedSlots[index].previewUrl);
    updatedSlots[index] = null;
    setImageSlots(updatedSlots);
    const remaining = updatedSlots.filter(Boolean);
    setPreview(remaining[0]?.previewUrl || null);
    setPreviewIndex(0);
    setError("");
    setSuccess(null);
  };

  const handlePrevImage = () => {
    if (selectedSlots.length <= 1) return;
    const ni = previewIndex === 0 ? selectedSlots.length - 1 : previewIndex - 1;
    setPreviewIndex(ni); setPreview(selectedSlots[ni].previewUrl);
  };

  const handleNextImage = () => {
    if (selectedSlots.length <= 1) return;
    const ni = (previewIndex + 1) % selectedSlots.length;
    setPreviewIndex(ni); setPreview(selectedSlots[ni].previewUrl);
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    const selectedFiles = imageSlots.filter(Boolean).map(s => s.file);
    if (!selectedFiles.length) { setError("Please select at least one face image."); return; }
    setError(""); setSuccess(null); setLoading(true);
    try {
      const result = await apiEnroll(fullName, gender, program, matricNumber, selectedFiles, isReenrolling);
      const count = Array.isArray(result) ? result.length : 1;
      setSuccess({
        records: Array.isArray(result) ? result : [result],
      });
      setEnrolledFaceCount(count);
      setAlreadyEnrolled(true);
      setFullName(""); setGender(""); setProgram(""); setMatricNumber("");
      clearImages();
    } catch (err) {
      setError(err.message === "Failed to fetch"
        ? "Could not reach the enrollment service. Check your connection and try again."
        : err.message || "Enrollment could not be completed. Please try again.");
    } finally {
      setLoading(false);
    }
  };

  const completedFields = [fullName.trim(), gender, program, matricNumber.trim()].filter(Boolean).length;
  const progress = Math.round(((completedFields / 4) * 0.5 + (selectedSlots.length / MAX_IMAGES) * 0.5) * 100);

  return (
    <main className={styles.workspacePage}>
      <header className={styles.workspaceHeader}>
        <span className={styles.workspaceEyebrow}><i /> FACE ENROLLMENT</span>
        <h1>Create Your Facial Profile</h1>
        <p>
          Register your face with the system by providing your details and uploading clear facial images.
          Your images will be processed to create the facial data used for future identity recognition.
        </p>
      </header>

      <div className={styles.workspaceProgress} aria-label={`Enrollment form ${progress}% complete`}>
        <div className={styles.progressTop}>
          <span className={styles.progressLabel}>Profile setup</span>
          <span className={styles.progressValue}>{completedFields}/4 details · {selectedSlots.length}/{MAX_IMAGES} images</span>
        </div>
        <div className={styles.progressTrack}>
          <div className={styles.progressFill} style={{ width: `${progress}%` }} />
        </div>
      </div>

      <div className={styles.workspaceGrid}>
        <form onSubmit={handleSubmit} className={styles.workspaceForm}>
          <section className={styles.workspaceCard}>
            <div className={styles.workspaceSectionHeader}>
              <span className={styles.workspaceSectionIcon}><FiUser /></span>
              <div><h2>Personal details</h2><p>Enter the information used for your enrollment record.</p></div>
            </div>
            {error && <div className={styles.workspaceError} role="alert"><FiAlertTriangle /><span>{error}</span></div>}

            <div className={styles.workspaceFields}>
              <label className={styles.workspaceField}>
                Full Name
                <input type="text" placeholder="e.g. Adewale Johnson" required value={fullName} onChange={e => setFullName(e.target.value)} disabled={loading} />
              </label>

              <label className={styles.workspaceField}>
                Gender
                <select value={gender} onChange={e => setGender(e.target.value)} required disabled={loading}>
                  <option value="">Select gender</option>
                  <option value="Male">Male</option>
                  <option value="Female">Female</option>
                  <option value="Other">Other</option>
                </select>
              </label>

              <label className={styles.workspaceField}>
                Program / Role
                <select value={program} onChange={e => setProgram(e.target.value)} required disabled={loading}>
                  <option value="">Select program</option>
                  <option value="Student">Student</option>
                  <option value="Staff">Staff</option>
                  <option value="Other">Other</option>
                </select>
              </label>

              <label className={styles.workspaceField}>
                Matric Number / ID
                <input type="text" placeholder="e.g. CSC/2021/001" required value={matricNumber} onChange={e => setMatricNumber(e.target.value)} disabled={loading} />
              </label>
            </div>
          </section>

          <section className={styles.workspaceCard}>
            <div className={styles.workspaceSectionHeader}>
              <span className={styles.workspaceSectionIcon}><FiCamera /></span>
              <div><h2>Face images</h2><p>Choose one to three photos. Drop files onto a slot or select them from your device.</p></div>
            </div>
            <div className={styles.workspaceSlots}>
              {imageSlots.map((slot, index) => (
                <div
                  key={index}
                  className={`${styles.workspaceSlot} ${slot ? styles.workspaceSlotSelected : ""} ${dragOverIndex === index ? styles.workspaceSlotDragOver : ""}`}
                  onDragOver={event => { event.preventDefault(); if (!loading) setDragOverIndex(index); }}
                  onDragLeave={event => {
                    if (!event.currentTarget.contains(event.relatedTarget)) setDragOverIndex(null);
                  }}
                  onDrop={event => {
                    event.preventDefault();
                    setDragOverIndex(null);
                    if (!loading) handleSlotChange(index, event.dataTransfer.files?.[0]);
                  }}
                  aria-busy={loading}
                >
                  <input
                    id={`enrollment-image-${index}`}
                    className={styles.visuallyHidden}
                    type="file"
                    accept="image/jpeg,image/png"
                    disabled={loading}
                    onChange={event => {
                      const file = event.target.files?.[0];
                      event.target.value = "";
                      handleSlotChange(index, file);
                    }}
                  />
                  {slot ? (
                    <img src={slot.previewUrl} alt={`Selected face image ${index + 1}`} className={styles.workspaceSlotImage} />
                  ) : (
                    <span className={styles.workspaceSlotIcon}><FiUploadCloud /></span>
                  )}
                  <div className={styles.workspaceSlotActions}>
                    <label className={styles.workspaceSlotPick} htmlFor={`enrollment-image-${index}`}>
                      <FiUploadCloud /> Upload Image
                    </label>
                    <button
                      type="button"
                      className={styles.workspaceSlotCamera}
                      onClick={() => {
                        if (imageSlots[index] && !imageSlots.some(item => !item)) {
                          setError(`You can select up to ${MAX_IMAGES} images. Remove an image before adding another.`);
                          return;
                        }
                        setCameraSlotIndex(index);
                      }}
                      disabled={loading}
                    >
                      <FiCamera /> Take a Photo
                    </button>
                  </div>
                  <span className={styles.workspaceSlotStatus}>
                    {slot ? `${(slot.file.size / 1024).toFixed(0)} KB · Ready to submit` : "Drop image here"}
                  </span>
                  {slot && (
                    <button type="button" className={styles.workspaceSlotRemove} onClick={() => handleRemoveSlot(index)} disabled={loading} aria-label={`Remove image ${index + 1}`}>
                      <FiX /> Remove
                    </button>
                  )}
                </div>
              ))}
            </div>
            <p className={styles.workspaceHint}><FiInfo /> JPG/JPEG/PNG only · maximum 100 KB each · up to {MAX_IMAGES} images.</p>
            {loading && (
              <div className={styles.workspaceProcessing} role="status" aria-live="polite">
                <FiLoader />
                <span><strong>Submitting enrollment</strong><small>Images are being prepared and sent. The recognition service will validate them, extract facial features, and save your profile.</small></span>
              </div>
            )}
            <button type="submit" className={styles.primaryButton} disabled={loading}>
              {loading ? <><FiLoader className={styles.workspaceSpinner} /> Processing enrollment...</> : <><FiShield /> {isReenrolling ? "Redo Enrollment" : "Enroll Faces"}</>}
            </button>
          </section>
        </form>

        <aside className={styles.workspaceAside}>
          <section className={styles.workspaceCard}>
            <div className={styles.workspaceSectionHeader}>
              <span className={styles.workspaceSectionIcon}><FiImage /></span>
              <div><h2>Image preview</h2><p>{preview ? `Image ${previewIndex + 1} of ${selectedSlots.length}` : "Your selected image will appear here."}</p></div>
            </div>
            <div className={styles.workspacePreview}>
              {preview ? <img src={preview} alt="Selected face image preview" /> : <div><FiCamera /><span>No image selected</span></div>}
              {selectedSlots.length > 1 && (
                <div className={styles.workspacePreviewControls}>
                  <button type="button" onClick={handlePrevImage} aria-label="Previous selected image">‹</button>
                  <span>{previewIndex + 1} / {selectedSlots.length}</span>
                  <button type="button" onClick={handleNextImage} aria-label="Next selected image">›</button>
                </div>
              )}
            </div>
          </section>

          <section className={styles.workspaceInfoCard}>
            <h2><FiInfo /> What happens next</h2>
            <p>The backend detects the face in each image, checks that the face is clear enough, generates its facial embedding, and stores the enrollment for matching.</p>
            <p>If an image cannot be processed, the backend will return the reason and your current enrollment will remain unchanged.</p>
          </section>
        </aside>
      </div>
      {cameraSlotIndex !== null && (
        <LiveCamera
          onCapture={file => {
            const targetIndex = imageSlots[cameraSlotIndex]
              ? imageSlots.findIndex(slot => !slot)
              : cameraSlotIndex;
            if (targetIndex < 0) {
              setError(`You can select up to ${MAX_IMAGES} images. Remove an image before adding another.`);
              return "You can select up to 3 images. Remove an image before adding another.";
            }
            return handleSlotChange(targetIndex, file);
          }}
          onClose={() => setCameraSlotIndex(null)}
        />
      )}
    </main>
  );
}

export default Enroll;
